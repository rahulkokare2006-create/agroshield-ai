export type Language = 'kn' | 'mr' | 'hi' | 'en';

// Helper to convert Western Arabic digits (0-9) to Kannada, Devanagari (Marathi/Hindi), or keep English
export function toLocalizedDigits(input: string | number, lang: Language): string {
  if (input === null || input === undefined) return '';
  const str = input.toString();
  if (lang === 'en') return str;

  const knDigits = ['೦', '೧', '೨', '೩', '೪', '೫', '೬', '೭', '೮', '೯'];
  const devDigits = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];

  const targetDigits = (lang === 'kn') ? knDigits : devDigits;
  return str.replace(/[0-9]/g, (digit) => targetDigits[parseInt(digit, 10)]);
}

